"""Packs the Purble Place sound files into addons/purble-place-sounds.js.

Browsers (Firefox for sure, Chrome too) won't let a page opened as a file (file://) read the
sound files next to it. The OS then loads this script, which carries the same sounds inline, and
the game uses them instead of fetching. Over http (start.bat) this script is not loaded at all.

Run it from anywhere after adding or changing a file in addons/purble-place/assets/sounds:
    python addons/build-purble-sounds.py
"""
import base64
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOUNDS = os.path.join(HERE, "purble-place", "assets", "sounds")
OUT = os.path.join(HERE, "purble-place-sounds.js")


def main():
    files = sorted(f for f in os.listdir(SOUNDS) if f.lower().endswith((".wav", ".mp3")))
    if not files:
        sys.exit("No .wav or .mp3 files found in " + SOUNDS)
    lines = [
        "/* Generated by addons/build-purble-sounds.py from addons/purble-place/assets/sounds. Don't edit by hand. */",
        "window.PURBLE_PLACE_SOUNDS = {",
    ]
    for name in files:
        with open(os.path.join(SOUNDS, name), "rb") as f:
            data = base64.b64encode(f.read()).decode("ascii")
        lines.append('  "%s": "%s",' % (name, data))
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote %s: %d sounds, %.1f MB" % (os.path.relpath(OUT), len(files), os.path.getsize(OUT) / 1024 / 1024))


if __name__ == "__main__":
    main()
